-- Run in the Supabase dashboard: SQL Editor → New query → paste → Run.
--
-- WARNING: this rebuilds the app's tables from scratch. It drops every app
-- table (and all rows in them) before recreating them. Auth users are kept;
-- the backfill at the bottom turns each existing account into a caretaker.
--
-- Roles
--   caretaker  Signs up with email + password. Manages their patients.
--   patient    Created by a caretaker in the app, never self-signed-up.
--              Logs in with a username (the app maps it to an internal
--              email address on the reserved .invalid domain).
--
-- Every auth user the app uses has exactly one row in public.profiles, which
-- is the single source of truth for role and caretaker. The app writes
-- profiles only from the server with the secret key (creating a patient also
-- creates their auth user, which needs the admin API anyway).
--
-- Data
--   contacts, tasks, places  Belong to a patient. The patient reads them;
--                            their caretaker reads and writes them.
--   task_completions         One row per checked-off task. Kept apart from
--                            tasks so a patient can tick a task without
--                            having write access to the task itself.
--   photos (storage bucket)  Private. Files live under <patient id>/; the
--                            patient and their caretaker read them, the
--                            caretaker uploads and deletes them.

drop table if exists
  public.task_completions,
  public.tasks,
  public.contacts,
  public.places,
  public.patients,
  public.profiles
  cascade;

-- Profiles

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('caretaker', 'patient')),
  name text not null check (length(trim(name)) > 0),
  -- Object path in the photos bucket, or '' for none.
  photo_path text not null default '',
  -- Patients only: login name, and the caretaker who manages them.
  -- Generated by the app from the patient's name: lowercase letters and digits.
  username text unique check (username ~ '^[a-z0-9]{1,30}$'),
  caretaker_id uuid,
  -- Always 'caretaker' when caretaker_id is set, so the foreign key below can
  -- only point at a caretaker's profile.
  caretaker_role text generated always as
    (case when caretaker_id is not null then 'caretaker' end) stored,
  created_at timestamptz not null default now(),

  constraint profiles_id_role_key unique (id, role),
  -- restrict: a caretaker can't be deleted while they still have patients,
  -- which would leave patient logins with nobody managing them.
  constraint profiles_caretaker_fkey foreign key (caretaker_id, caretaker_role)
    references public.profiles (id, role) on delete restrict,
  constraint profiles_role_fields check (
    (role = 'patient' and username is not null and caretaker_id is not null)
    or (role = 'caretaker' and username is null and caretaker_id is null)
  )
);

create index profiles_caretaker_id_idx on public.profiles (caretaker_id);

-- Patient data

create table public.contacts (
  id bigint generated always as identity primary key,
  patient_id uuid not null references public.profiles (id) on delete cascade,
  name text not null,
  full_name text not null,
  relationship text not null,
  contact_group text not null check (contact_group in ('family', 'friends', 'care')),
  about text not null default '',
  schedule text not null default '',
  phone text not null default '',
  photo_path text not null default '',
  created_at timestamptz not null default now()
);

create table public.tasks (
  id bigint generated always as identity primary key,
  patient_id uuid not null references public.profiles (id) on delete cascade,
  text text not null,
  created_at timestamptz not null default now()
);

create table public.task_completions (
  task_id bigint primary key references public.tasks (id) on delete cascade,
  completed_at timestamptz not null default now()
);

create table public.places (
  id bigint generated always as identity primary key,
  patient_id uuid not null references public.profiles (id) on delete cascade,
  name text not null,
  description text not null default '',
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  created_at timestamptz not null default now()
);

create index contacts_patient_id_idx on public.contacts (patient_id);
create index tasks_patient_id_idx on public.tasks (patient_id);
create index places_patient_id_idx on public.places (patient_id);

-- Data API access
-- New tables aren't exposed to the Data API automatically; grant signed-in
-- users exactly what they need (RLS below decides which rows). No anon access.

revoke all on
  public.profiles, public.contacts, public.tasks, public.task_completions, public.places
  from anon, authenticated;
grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.contacts, public.tasks, public.places to authenticated;
grant select, insert, delete on public.task_completions to authenticated;

alter table public.profiles enable row level security;
alter table public.contacts enable row level security;
alter table public.tasks enable row level security;
alter table public.task_completions enable row level security;
alter table public.places enable row level security;

-- Row level security
-- "My patients" = profiles whose caretaker_id is the signed-in user. The
-- subqueries on profiles run under the profiles policy, which allows exactly
-- that lookup.

create policy "Read own profile and own patients" on public.profiles
  for select to authenticated
  using (id = (select auth.uid()) or caretaker_id = (select auth.uid()));

-- contacts
create policy "Patient and caretaker read contacts" on public.contacts
  for select to authenticated
  using (
    patient_id = (select auth.uid())
    or patient_id in (select id from public.profiles where caretaker_id = (select auth.uid()))
  );
create policy "Caretaker adds contacts" on public.contacts
  for insert to authenticated
  with check (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())));
create policy "Caretaker edits contacts" on public.contacts
  for update to authenticated
  using (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())))
  with check (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())));
create policy "Caretaker deletes contacts" on public.contacts
  for delete to authenticated
  using (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())));

-- tasks
create policy "Patient and caretaker read tasks" on public.tasks
  for select to authenticated
  using (
    patient_id = (select auth.uid())
    or patient_id in (select id from public.profiles where caretaker_id = (select auth.uid()))
  );
create policy "Caretaker adds tasks" on public.tasks
  for insert to authenticated
  with check (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())));
create policy "Caretaker edits tasks" on public.tasks
  for update to authenticated
  using (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())))
  with check (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())));
create policy "Caretaker deletes tasks" on public.tasks
  for delete to authenticated
  using (patient_id in (select id from public.profiles where caretaker_id = (select auth.uid())));

-- task_completions: anyone who can see the task (the patient or their
-- caretaker, via the tasks policy) can tick or untick it.
create policy "Patient and caretaker read completions" on public.task_completions
  for select to authenticated
  using (task_id in (select id from public.tasks));
create policy "Patient and caretaker tick tasks" on public.task_completions
  for insert to authenticated
  with check (task_id in (select id from public.tasks));
create policy "Patient and caretaker untick tasks" on public.task_completions
  for delete to authenticated
  using (task_id in (select id from public.tasks));

